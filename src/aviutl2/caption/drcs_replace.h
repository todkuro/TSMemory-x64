//----------------------------------------------------------------------------
//	外字 (DRCS) を本物の文字に置き換える
//
//	放送の外字の多くは、**Unicode に実在する文字**をたまたま字形の
//	ビットマップとして送っているだけ (『』〜㊙｟｠、德 髙 﨑 塚 𠮷 等)。
//	対応表で本物の文字に直せば、
//
//	  ・**その回の取り込みから出る** (フォントの登録が要らない)
//	  ・テキストとして編集・検索・コピーできる
//	  ・縁取りも色も大きさも普通の文字と同じに効く
//
//	AviUtl2 はフォントの登録を初期化時にしか受け付けない為、この経路が
//	無いと「初めて見た外字は次の起動まで出ない」事になる
//	(drcs_store.h を参照)。ここで賄えなかった分だけが貯め込みに回る。
//
//	**鍵は字形のビットマップの md5。**ARIB の符号 (0x21 から順) の意味は
//	番組ごとに変わるので鍵にならない。
//----------------------------------------------------------------------------
#pragma once

#include <windows.h>

#include <string>

#include "drcs_ttf.h"

//	利用者の対応表を読む (初期化の時に 1 度だけ)。
//
//	pszIniFile … プラグインの ini。同じフォルダの TSMemoryDrcsMap.txt を読む
//	戻り値     … 読めた行数
int TSMemoryDrcsReplaceLoad(LPCWSTR pszIniFile);

//	字形を本物の文字に置き換える。
//
//	Glyph  … 字形
//	pOut   … 置き換える文字 (UTF-16。𠮷 のような 2 コード単位の文字もある)
//	pMd5   … 見つからなかった時に利用者へ知らせる md5 (32 桁の 16 進)
//	戻り値 … 置き換えられたら true
//
//	利用者の対応表を先に見る (組み込みの表を上書きできる)
bool TSMemoryDrcsReplaceFind(const TSMemoryDrcsGlyph &Glyph,
							 std::wstring *pOut, std::wstring *pMd5);

//	md5 を直接渡して引く (上の関数の中身)。
//	字形を用意せずに表だけを試せるので、テストから使う
bool TSMemoryDrcsReplaceFindByMd5(const BYTE *pMd5_16, std::wstring *pOut);
