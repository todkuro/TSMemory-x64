//----------------------------------------------------------------------------
//	ARIB STD-B24 の 8 単位符号を解く
//
//	字幕の本文は独自の符号系で書かれている。1 バイトの領域 (GL/GR) に
//	どの文字集合を割り当てるかを、エスケープと単/複シフトで切り替えながら
//	進む。制御符号で色・大きさ・位置も指定される。
//
//	ここでは「読める形」に直すところまでを担う。
//	AviUtl2 のテキスト制御文字への変換は呼び出し側で行う
//	(<#色> <s大きさ> <p座標> 等に写す)。
//
//	漢字は JIS X 0208 なので Shift_JIS に直して Windows に変換させる。
//	14KB の対応表を抱えずに済む。
//----------------------------------------------------------------------------
#pragma once

#include <windows.h>

#include <string>
#include <vector>

//	復号した結果の 1 項目
enum class AribItemType {
	Text,			// 本文
	Drcs,			// 外字。A = 符号 (どの字形かは別途 DRCS 定義から引く)
	Color,			// A = 前景色 (0-15)
	BackColor,		// A = 背景色 (0-15)
	//	A = 横スケール, B = 縦スケール (どちらも 10 倍した整数)。
	//	**縦横を別に持つ。**SZX には「縦だけ 2 倍」「横だけ 2 倍」があり、
	//	1 つの値では表せない
	//	  SSZ 小型 = 5,5 / MSZ 中型 = 5,10 / NSZ 標準 = 10,10
	//	  SZX 0x41 = 10,20 (縦だけ) / 0x44 = 20,10 (横だけ) / 0x45 = 20,20
	Size,
	//	ORN (文字外縁 / 縁取り)。A = 0 なし / 1 縁取り、B = 縁の色 (0-127)。
	//	**放送が実際に送って来る。**TVCaptionMod2 は縁の太さだけを
	//	これで切り替えており、色は見ていない (「着色対応は省略」)
	Ornament,
	//	文字修飾。A はビットの組み合わせ
	//	  1 = 太字 / 2 = 斜体 (MDF)
	//	  4 = 下線 (STL / SPL)
	//	  8 = 囲み (HLC)
	//
	//	**AviUtl2 のテキストに下線と囲みは無い。**
	//	`aviutl2.txt` の文字スタイルは B (太字) / I (斜体) /
	//	S (取り消し線) だけで、下線も囲みも制御文字が無い。
	//	復号はするが出力には使えない (caption.dll も下線を太字で
	//	代用しており、そのまま出す術は無い)
	Decoration,
	Position,		// A = X, B = Y (字幕平面のドット。APS も ACPS もここに来る)
	ClearScreen,	// 画面消去 (CS)
	LineBreak,		// 改行 (APD / APR)
	Geometry,		// A = 文字の高さ, B = 字幕平面の高さ (どちらもドット)
};

struct AribItem {
	AribItemType Type;
	std::wstring Text;		// Text の時だけ
	int A = 0;
	int B = 0;

	//	Position の時だけ。その時点の行送りの高さ (SSM + SVS)。
	//	ルビは半行だけ上下するので、改行かどうかの判定に要る。
	//
	//	Text / Drcs の時は「この文字を書き終えた後のペンの X」。
	//	**行の幅を出すのに要る。**AviUtl2 のテキストオブジェクトは
	//	X が「行の中央」なので、左端だけでは位置を決められない
	int C = 0;

	//	Position の時だけ。その時点の 1 文字分の送り幅 (SSM + SHS)。
	//	**同じ高さで横に飛んだ時に行を割る**のに要る。
	//	複数の話者を同時に別の場所へ出す字幕で起こり、割らないと
	//	離れた場所の文字が 1 つのオブジェクトに繋がってしまう
	//
	//	Text / Drcs の時は「この文字を書き始めた時のペンの X」。
	//	**ルビを本文の字に対応付けるのに要る。**ルビは本文の 1 行上に
	//	まとまりごとに位置を打って書かれるので、X の重なりで
	//	どの字に掛かるかを決める
	int D = 0;
};

//	字幕文データ (data_unit の本文) を解く。
//	pData/Size … データユニットの中身 (0x20 = 本文)
//	pOut       … 解けた項目が順に入る
void AribDecodeText(const BYTE *pData, size_t Size, std::vector<AribItem> *pOut);

//	項目の並びから本文だけを取り出す (確認用)。
//	外字は pszDrcs (既定は "＃") に置き換える
std::wstring AribItemsToPlainText(const std::vector<AribItem> &Items,
								  LPCWSTR pszDrcs = L"＃");
